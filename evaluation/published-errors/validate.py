# The experiment spec enumerates the defect kinds it calls preventable at entry:
# missing required property, wrong datatype, value outside sh:in, malformed IRI,
# missing lang tag. These are the constraint components that correspond to that
# list one-for-one.
#
# Everything else in PREVENTABLE is preventable by our own reading rather than
# by the spec's enumeration - sh:maxCount (a form generated from the shape emits
# one field, so it cannot over-supply), sh:class on a node the record itself
# describes (the form knows the class of the node it is building), sh:minLength.
# Defensible, but ours. The share is therefore reported twice: once over
# everything bucketed preventable, and once over this list alone, which is the
# floor under the second headline.
SPEC_LISTED = {
    "MinCountConstraintComponent",      # missing required property
    "DatatypeConstraintComponent",      # wrong datatype
    "InConstraintComponent",            # value outside sh:in
    "HasValueConstraintComponent",      # value outside sh:in
    "NodeKindConstraintComponent",      # malformed IRI
    "PatternConstraintComponent",       # malformed IRI
    "UniqueLangConstraintComponent",    # missing / duplicated language tag
    "LanguageInConstraintComponent",    # missing / duplicated language tag
}

# ------------------------------------------------------------- value shapes
# For the properties carrying most of the defects, record what *kind* of value
# is actually present. Categories are vocabulary-level - a namespace or a
# datatype - and never a value, a host or anything else that could identify a
# publisher. This is what backs the "what the defects actually are" table, so
# that no claim about them has to be typed by hand.
AUTHORITY = "http://publications.europa.eu/resource/authority/"
ADMS = Namespace("http://www.w3.org/ns/adms#")
IANA_MEDIA = re.compile(r"^https?://(www\.)?iana\.org/assignments/media-types/")
ADMS_LEGACY = "http://purl.org/adms/status/"

VALUE_SHAPE_RULES: dict[str, list] = {
    "dct:format": [
        (lambda s: s.startswith(AUTHORITY + "file-type/"),
         "IRI from the mandated EU File Type table"),
        (lambda s: bool(IANA_MEDIA.match(s)),
         "IRI from the IANA registry that dcat:mediaType mandates"),
        (lambda s: s.startswith(AUTHORITY),
         "IRI from a different EU authority table"),
    ],
    "dcat:mediaType": [
        (lambda s: bool(IANA_MEDIA.match(s)),
         "IRI from the mandated IANA media-type registry"),
        (lambda s: s.startswith(AUTHORITY + "file-type/"),
         "IRI from the EU File Type table that dct:format mandates"),
        (lambda s: s.startswith(AUTHORITY),
         "IRI from a different EU authority table"),
    ],
    "adms:status": [
        (lambda s: s.startswith(AUTHORITY + "distribution-status/"),
         "IRI from the mandated EU Distribution status table"),
        (lambda s: s.startswith(ADMS_LEGACY),
         "IRI from the superseded purl.org/adms/status vocabulary"),
        (lambda s: s.startswith(AUTHORITY),
         "IRI from a different EU authority table"),
    ],
}

VALUE_SHAPES: Counter = Counter()


def value_shape(prop: str, v) -> str:
    """Categorise one value. Vocabulary-level only - never echoes the value."""
    if isinstance(v, Literal):
        if prop == "dcat:byteSize":
            return (f"typed {str(v.datatype).replace(str(XSD), 'xsd:')}"
                    if v.datatype else "plain literal, no datatype")
        return "plain literal where the profile mandates an IRI"
    s = str(v)
    if prop == "dcat:byteSize":
        return "IRI where a literal is required"
    for test, label in VALUE_SHAPE_RULES.get(prop, []):
        if test(s):
            return label
    return "IRI from outside any mandated vocabulary"


def collect_value_shapes(g: Graph, root: URIRef) -> None:
    for dist in g.objects(root, DCAT.distribution):
        for prop, name in ((DCT["format"], "dct:format"),
                           (DCAT.mediaType, "dcat:mediaType"),
                           (ADMS.status, "adms:status"),
                           (DCAT.byteSize, "dcat:byteSize")):
            for v in g.objects(dist, prop):
                VALUE_SHAPES[(name, value_shape(name, v))] += 1

# EU frequency authority code -> nominal period in days. Used only for L3
# staleness: a record is stale when its own declared frequency says it should
# have been refreshed and it has not been.
FREQ_DAYS = {
    "CONT": 1, "DAILY": 1, "DAILY_2": 1, "TWICE_A_DAY": 1,
    "WEEKLY": 7, "WEEKLY_2": 4, "WEEKLY_3": 3, "BIWEEKLY": 14,
    "MONTHLY": 30, "MONTHLY_2": 15, "MONTHLY_3": 10, "BIMONTHLY": 61,
    "QUARTERLY": 91, "ANNUAL": 365, "ANNUAL_2": 182, "ANNUAL_3": 121,
    "BIENNIAL": 730, "TRIENNIAL": 1095,
}
# Flag only when overdue by 3x the declared period AND by at least a year. A
# dataset that says CONT and was touched last month is not evidence of anything;
# one that says CONT and was last touched in 2019 is.
STALE_FACTOR = 3
STALE_FLOOR_DAYS = 365

# The empty string is deliberately NOT here: an empty mandatory field is
# caught by the sh:minLength constraint in L2 and is preventable at entry, which
# is not what this list is for.
PLACEHOLDERS = {
    "-", "--", ".", "n/a", "na", "n.a.", "none", "null", "nil", "tbd",
    "to be defined", "unknown", "unspecified", "no description",
    "no description available", "not available", "test", "todo", "xxx",
    "sin descripcion", "sin descripción", "keine angabe", "desconocido",
    "no aplica", "string", "sample", "example", "lorem ipsum",
}

MT_LANG = re.compile(r"-t-[a-z]{2,3}(-[a-z0-9]+)*-t0-", re.IGNORECASE)


def is_machine_translation(lit: Literal) -> bool:
    return bool(lit.language and MT_LANG.search(lit.language))


# ---------------------------------------------------------------- graph cleaning


def clean_record(g: Graph, root: URIRef) -> Graph:
    """Keep only what the publisher's record says, reachable from the dataset.

    Removed: dqv quality annotations (computed by the aggregator), machine
    translations (produced by the aggregator), and every node not reachable
    forward from the dataset - which drops the aggregator's catalogue and
    catalogue-record containers.
    """
    out = Graph()
    for pre, ns in g.namespaces():
        out.bind(pre, ns)

    seen: set = set()
    stack = [root]
    while stack:
        node = stack.pop()
        if node in seen:
            continue
        seen.add(node)
        for p, o in g.predicate_objects(node):
            if p.startswith(str(DQV)):
                continue
            if isinstance(o, Literal) and is_machine_translation(o):
                continue
            if isinstance(o, URIRef) and str(o).startswith(
                "http://data.europa.eu/88u/metrics/"
            ):
                continue
            out.add((node, p, o))
            if isinstance(o, (URIRef, BNode)):
                stack.append(o)
    return out


# ---------------------------------------------------------------- SHACL running


def run_rudof(stage: Path, out_path: Path) -> dict:
    """Hand the staged corpus to rudof and read its report back.

    One node process, one wasm instance, shapes parsed once per layer. The
    raw report is written to `data/stage/` rather than kept in memory only:
    `preventability.py` needs the per-defect value facts and there is no reason
    for it to re-validate the corpus to get them.
    """
    subprocess.run(
        ["node", str(HERE / "rudof_validate.mjs"), str(stage), str(out_path)],
        check=True, cwd=HERE,
    )
    return json.loads(out_path.read_text())


def classify(rows: list[dict], m: dict) -> tuple[list[dict], Counter]:
    """Triage every validation result into defect / scaffolding / not assessable.

      * an `sh:class`/`sh:node` result whose *value* is a node the harvest never
        described is not assessable - the record may well be fine and our
        extraction short;
      * a result whose *focus* is not described is scaffolding (an EU authority
        concept we typed so that a constraint on the record could be evaluated
        at all) or, failing that, not assessable;
      * everything else is a defect charged to the record.

    "Described" is "has an outgoing triple in the record graph". For an IRI that
    is a lookup by name against the staging metadata. A blank node has no name
    that survives serialization - the parser mints its own label - so its
    out-degree is measured by the engine holding the graph and carried on the
    result, which is what `focus_out` / `value_out` are for.
    """
    described = set(m["described_iris"])
    reftype = set(m["reftype_iris"])
    defects: list[dict] = []
    counts: Counter = Counter()

    for r in rows:
        comp = r["component"]
        fk, fv = r["focus"]["kind"], r["focus"]["value"]
        f_described = (r["focus_out"] > 0) if fk == "BlankNode" else fv in described

        if comp in ("ClassConstraintComponent", "NodeConstraintComponent") \
                and r["value"] is not None \
                and r["value"]["kind"] in ("NamedNode", "BlankNode"):
            v_described = (r["value_out"] > 0
                           if r["value"]["kind"] == "BlankNode"
                           else r["value"]["value"] in described)
            if not v_described:
                counts["not_assessable"] += 1
                counts[("na_path", short_path(r["path"]), comp)] += 1
                continue

        if not f_described:
            if fk == "NamedNode" and fv in reftype:
                counts["scaffolding"] += 1
            else:
                counts["not_assessable"] += 1
                counts[("na_path", "(focus node not described)", comp)] += 1
            continue

        types = (r["focus_types"] if fk == "BlankNode"
                 else m["iri_types"].get(fv, []))
        defects.append({
            "component": comp,
            "path": short_path(r["path"]),
            "focus_class": focus_class_of(types),
            # Kept for preventability.py, which needs to know *how* a value was
            # wrong - a literal where an IRI belongs, a wrong datatype IRI, or a
            # right datatype IRI with an ill-typed lexical form are three
            # different questions to ask of a form.
            "value_kind": None if r["value"] is None else r["value"]["kind"],
            "value_datatype": (r["value"] or {}).get("datatype"),
        })
        counts["defect"] += 1
    return defects, counts


def focus_class_of(types: list[str]) -> str:
    """`focus_class`, but from a list of type IRIs rather than from a graph."""
    short = [t.rsplit("/", 1)[-1].rsplit("#", 1)[-1] for t in types]
    for want in ("Dataset", "Distribution", "Kind", "Agent", "PeriodOfTime",
                 "Identifier", "Checksum", "Concept", "Location"):
        if want in short:
            return want
    return short[0] if short else "(untyped)"


def drop_dangling_property_shapes(shapes: Graph) -> list[str]:
    """Remove `sh:property` links whose target has no triples at all.

    DCAT-AP 3.0.1's `dcat:DataServiceShape` links two property shapes that do
    not exist anywhere in the file: the objects of those two `sh:property`
    triples are IRIs with no other triple about them in the document. That is a
    defect in the published profile and it is reported as one.

    An empty property shape constrains nothing - it has no `sh:path` and no
    constraint parameter - so dropping the link cannot hide a violation, and the
    corpus run is unaffected either way. The links are dropped so that the
    shapes graph the validator sees contains only shapes that say something.
    `conformance.py` checks the "unaffected either way" claim rather than
    asserting it: it runs rudof against a deliberately-violating
    `dcat:DataService` under both the published and the de-dangled shapes and
    requires the same answer.
    """
    dangling = [(s, o) for s, o in shapes.subject_objects(SH.property)
                if not any(True for _ in shapes.predicate_objects(o))]
    for s, o in dangling:
        shapes.remove((s, SH.property, o))
    return [f"{str(s).rsplit('#', 1)[-1]} -> {str(o).rsplit('#', 1)[-1]}"
            for s, o in dangling]


def focus_class(g: Graph, node) -> str:
    types = [str(t).rsplit("/", 1)[-1].rsplit("#", 1)[-1]
             for t in g.objects(node, RDF.type)]
    for want in ("Dataset", "Distribution", "Kind", "Agent", "PeriodOfTime",
                 "Identifier", "Checksum", "Concept", "Location"):
        if want in types:
            return want
    return types[0] if types else "(untyped)"


def short_path(path: str) -> str:
    if not path:
        return ""
    for pre, ns in (("dct:", str(DCT)), ("dcat:", str(DCAT)), ("foaf:", str(FOAF)),
                    ("vcard:", "http://www.w3.org/2006/vcard/ns#"),
                    ("adms:", "http://www.w3.org/ns/adms#"),
                    ("spdx:", "http://spdx.org/rdf/terms#"),
                    ("skos:", "http://www.w3.org/2004/02/skos/core#"),
                    ("owl:", "http://www.w3.org/2002/07/owl#"),
                    ("prov:", "http://www.w3.org/ns/prov#"),
                    ("odrl:", "http://www.w3.org/ns/odrl/2/"),
                    ("dcatap:", "http://data.europa.eu/r5r/"),
                    ("locn:", "http://www.w3.org/ns/locn#"),
                    ("time:", "http://www.w3.org/2006/time#"),
                    ("rdfs:", "http://www.w3.org/2000/01/rdf-schema#")):
        if path.startswith(ns):
            return pre + path[len(ns):]
    return path


# ------------------------------------------------------------------ L3 checks


def parse_date(lit) -> datetime | None:
    if not isinstance(lit, Literal):
        return None
    s = str(lit).strip()
    for fmt in ("%Y-%m-%dT%H:%M:%S%z", "%Y-%m-%dT%H:%M:%S.%f%z",
                "%Y-%m-%dT%H:%M:%SZ", "%Y-%m-%dT%H:%M:%S.%fZ",
                "%Y-%m-%dT%H:%M:%S", "%Y-%m-%d", "%Y"):
        try:
            d = datetime.strptime(s, fmt)
            return d if d.tzinfo else d.replace(tzinfo=timezone.utc)
        except ValueError:
            continue
    return None


def l3_checks(g: Graph, root: URIRef, link_status: str | None) -> list[dict]:
    """Defects a shape cannot express. Deliberately conservative."""
    found = []

    # (1) dead distribution link, as observed by linkcheck.py
    if link_status in ("gone", "dns_fail", "conn_fail"):
        found.append({"component": "DeadLink", "path": "dcat:accessURL",
                      "focus_class": "Distribution",
                      "label": "distribution link does not resolve"})

    # (2) the record's own declared update frequency is contradicted
    freq = g.value(root, DCT.accrualPeriodicity)
    modified = parse_date(g.value(root, DCT.modified)) or \
        parse_date(g.value(root, DCT.issued))
    if isinstance(freq, URIRef) and modified is not None:
        code = str(freq).rsplit("/", 1)[-1]
        period = FREQ_DAYS.get(code)
        if period is not None:
            overdue = (HARVEST_DATE - modified).days
            if overdue > max(STALE_FLOOR_DAYS, STALE_FACTOR * period):
                found.append({"component": "StaleVsDeclaredFrequency",
                              "path": "dct:modified", "focus_class": "Dataset",
                              "label": "not refreshed at its own declared frequency"})

    # (3) placeholder value in a human-facing field
    for prop, name in ((DCT.title, "dct:title"), (DCT.description, "dct:description"),
                       (DCAT.keyword, "dcat:keyword")):
        for node in [root] + list(g.objects(root, DCAT.distribution)):
            for v in g.objects(node, prop):
                if not isinstance(v, Literal):
                    continue
                norm = re.sub(r"<[^>]+>", " ", str(v)).strip().lower().strip(" .,:;-_")
                if norm in PLACEHOLDERS:
                    found.append({"component": "PlaceholderValue", "path": name,
                                  "focus_class": focus_class(g, node),
                                  "label": "placeholder value, structurally valid"})
                    break
    return found


# ----------------------------------------------------------------------- main


def stage_corpus() -> tuple[list[dict], list[str], int, int]:
    """Build every record's validation graph once and write it to data/stage/.

    The engine runs out-of-process, so the graph has to be serialized anyway.
    Doing it in one explicit stage rather than implicitly per validate() call
    has two payoffs: the bytes rudof parses are on disk and can be inspected,
    and the parse can be accounted for - rdflib's triple count against rudof's,
    per record. A validator that discards part of its input and then reports
    conformance is not lenient, it is silent, and that was one of the two bugs
    the retired pySHACL cross-check found. It is now a standing check rather
    than a comparison against another engine.

    Returns (records, dangling, parse_failures, incomplete). Each record carries
    everything the classifier and the summary need that is a fact about the
    *record* graph rather than about the validation report.
    """
    STAGE.mkdir(parents=True, exist_ok=True)
    manifest = list(csv.DictReader((DATA / "manifest.csv").open()))

    l1 = Graph()
    l1.parse(DATA / "dcat-ap-3.0.1" / "dcat-ap-SHACL.ttl", format="turtle")
    dangling = drop_dangling_property_shapes(l1)
    if dangling:
        print(f"note: dropped {len(dangling)} dangling sh:property link(s) from "
              f"the published DCAT-AP shapes: {dangling}", file=sys.stderr)
    l1.serialize(STAGE / "L1.ttl", format="turtle")

    l2 = Graph()
    l2.parse(DATA / "vocab-shapes.ttl", format="turtle")
    l2.serialize(STAGE / "L2.ttl", format="turtle")

    # sh:class walks rdfs:subClassOf* in the DATA graph, so the subclass axioms
    # have to be there or every vcard:Individual contact point fails an
    # sh:class vcard:Kind that it actually satisfies. Only subclass axioms are
    # merged - see ontology.py.
    hierarchy = Graph()
    hierarchy.parse(DATA / "class-hierarchy.ttl", format="turtle")

    # rdf:type of the external IRIs the records reference (EU authority
    # concepts, publisher agents), as the aggregator's own store asserts them.
    # Without these, `sh:class dct:LinguisticSystem` on `dct:language` fails for
    # every record that correctly uses the mandated vocabulary. Used only to let
    # constraints on the *referring* record be evaluated: a violation whose focus
    # node lives only here is not assessable, because "described" is asked of
    # the record graph, not of the validation graph.
    reftypes = Graph()
    rt = DATA / "ref-types.ttl"
    if rt.exists():
        reftypes.parse(rt, format="turtle")
    else:
        print("note: data/ref-types.ttl absent - sh:class results on external "
              "vocabulary IRIs will all fall into 'not assessable'",
              file=sys.stderr)

    records: list[dict] = []
    parse_failures = 0
    incomplete = 0          # records whose second harvest query timed out

    for i, rec in enumerate(manifest, 1):
        path = RAW / f"{rec['key']}.ttl"
        g = Graph()
        try:
            g.parse(path, format="turtle")
        except Exception:
            parse_failures += 1
            continue
        if "Q_DIST_LEAVES timed out" in path.read_text():
            incomplete += 1
        root = URIRef(rec["dataset_iri"])
        cg = clean_record(g, root)
        collect_value_shapes(cg, root)
        # What the validator sees: the record, the subclass axioms, and the
        # types of the external IRIs *this* record references. Scoped per record
        # on purpose - dumping every authority concept into every data graph
        # would make skos:ConceptShape target thousands of nodes that have
        # nothing to do with the record.
        vg = cg + hierarchy
        for o in set(cg.objects()):
            if isinstance(o, URIRef):
                for t in reftypes.objects(o, RDF.type):
                    vg.add((o, RDF.type, t))
        vg.serialize(STAGE / f"{rec['key']}.ttl", format="turtle")

        titles = list(cg.objects(root, DCT.title))
        records.append({
            "key": rec["key"],
            "catalogue": rec["catalogue"],
            "n_triples": len(cg),
            "staged_triples": len(vg),
            "mt_literals": sum(1 for _, _, o in g
                               if isinstance(o, Literal)
                               and is_machine_translation(o)),
            # descriptive, not a defect: does the record carry a language tag
            "untagged_title": bool(titles) and not any(
                isinstance(t, Literal) and t.language for t in titles),
            "has_description": bool(list(cg.objects(root, DCT.description))),
            "l3": l3_checks(cg, root, LINKS.get(rec["key"])),
            # Everything the classifier needs about the *record* graph. Blank
            # nodes are deliberately absent: their labels are minted by whoever
            # parsed the file, so they are described by out-degree instead.
            "meta": {
                "described_iris": sorted(
                    {str(s) for s in set(cg.subjects()) if isinstance(s, URIRef)}),
                "iri_types": {
                    str(s): sorted(str(t) for t in cg.objects(s, RDF.type))
                    for s in set(cg.subjects()) if isinstance(s, URIRef)},
                "reftype_iris": sorted(
                    {str(s) for s in set(cg.objects())
                     if isinstance(s, URIRef)
                     and any(True for _ in reftypes.predicate_objects(s))}),
            },
        })
        if i % 50 == 0:
            print(f"  staged {i}/{len(manifest)}")

    (STAGE / "keys.json").write_text(json.dumps([r["key"] for r in records]))
    (STAGE / "meta.json").write_text(
        json.dumps({r["key"]: r["meta"] for r in records}))
    (STAGE / "dangling.json").write_text(json.dumps(dangling))
    return records, dangling, parse_failures, incomplete


LINKS: dict[str, str] = {}


def main() -> None:
    frame = json.loads((DATA / "sample-frame.json").read_text())

    lc = DATA / "linkcheck.csv"
    if lc.exists():
        LINKS.update({r["key"]: r["status"] for r in csv.DictReader(lc.open())})
    else:
        print("note: data/linkcheck.csv absent - L3 dead-link check skipped",
              file=sys.stderr)

    print("staging validation graphs…")
    records, dangling, parse_failures, incomplete = stage_corpus()
    DANGLING[:] = dangling
    print(f"staged {len(records)} records")

    print("validating with rudof…")
    ru = run_rudof(STAGE, STAGE / "rudof-raw.json")
    engine = {"name": "rudof (wasm)", "package": ru["package"],
              "version": ru["version"], "node": ru["node"]}
    print(f"  {engine['package']}@{engine['version']}")

    per_record: list[dict] = []
    na_paths: Counter = Counter()

    for r in records:
        key = r["key"]
        defects: list[dict] = []
        not_assessable = 0
        scaffolding = 0
        engine_errors = 0

        for layer in ("L1", "L2"):
            rows = ru["records"].get(key, {}).get(layer)
            if rows is None:
                engine_errors += 1
                print(f"  {layer} engine error on one record: "
                      f"{ru['errors'].get(key, {}).get(layer)}", file=sys.stderr)
                continue
            got, counts = classify(rows, r["meta"])
            not_assessable += counts["not_assessable"]
            scaffolding += counts["scaffolding"]
            for k, v in counts.items():
                if isinstance(k, tuple):
                    na_paths[k[1:]] += v
            for d in got:
                defects.append({
                    "layer": layer,
                    "component": d["component"],
                    "path": d["path"],
                    "focus_class": d["focus_class"],
                    "bucket": "preventable",
                    "label": PREVENTABLE.get(d["component"], d["component"]),
                })

        # A record the parser refuses is not a clean record. It is a record no
        # validator can say anything about, which is strictly worse than a
        # constraint violation, and counting it as conformant would be the same
        # silent pass that rudof's own parser bug used to produce. It goes in
        # L3 because L3 is exactly "a defect no SHACL profile can express":
        # there is no shape that catches an IRI the grammar excludes, since the
        # triple never reaches the graph. Note that this one *is* preventable at
        # entry by a form that checks IRI well-formedness before writing - which
        # ours does not yet do (see the form backlog) - so the "not preventable"
        # bucket is, for these, a statement about SHACL and not about forms.
        if ru["loaded_quads"].get(key) is None:
            r["l3"].insert(0, {
                "component": "UnparseableRecord",
                "path": "",
                "focus_class": "Dataset",
                "label": "record carries an IRI a conformant Turtle parser "
                         "must reject",
            })

        for d in r["l3"]:
            defects.append({
                "layer": "L3",
                "component": d["component"],
                "path": d["path"],
                "focus_class": d["focus_class"],
                "bucket": "not_preventable",
                "label": d["label"],
            })

        per_record.append({
            "key": key,
            "catalogue": r["catalogue"],
            "n_triples": r["n_triples"],
            "staged_triples": r["staged_triples"],
            "rudof_quads": ru["loaded_quads"].get(key),
            "mt_literals": r["mt_literals"],
            "l1": sum(1 for d in defects if d["layer"] == "L1"),
            "l2": sum(1 for d in defects if d["layer"] == "L2"),
            "l3": sum(1 for d in defects if d["layer"] == "L3"),
            "not_assessable": not_assessable,
            "scaffolding_results": scaffolding,
            "engine_errors": engine_errors,
            "untagged_title": r["untagged_title"],
            "has_description": r["has_description"],
            "defects": defects,
        })

    anon = anonymise(per_record)

    RESULTS.mkdir(exist_ok=True)
    with (RESULTS / "violations.csv").open("w", newline="") as fh:
        cols = ["record", "layer", "component", "focus_class", "path",
                "bucket", "label"]
        w = csv.DictWriter(fh, fieldnames=cols)
        w.writeheader()
        for pr in sorted((p for p in per_record if p["defects"]),
                         key=lambda r: anon[r["key"]]):
            # rows sorted within the record too: rudof iterates a node shape's
            # property shapes in hash order, so result order varies between
            # runs. Without this the committed file churns on every re-run even
            # when nothing changed.
            for d in sorted(pr["defects"], key=lambda d: tuple(d[c] for c in cols[1:])):
                w.writerow({"record": anon[pr["key"]], **d})

    summary = build_summary(per_record, frame, parse_failures, bool(LINKS))
    summary["engine"] = engine
    summary["incomplete_harvest"] = incomplete
    # Aggregate only; the per-record statuses stay out of the repository.
    summary["linkcheck_distribution"] = dict(rank(Counter(LINKS.values())))
    summary["linkcheck_counted_dead"] = sum(
        v for k, v in Counter(LINKS.values()).items()
        if k in ("gone", "dns_fail", "conn_fail"))
    summary["not_assessable_by_path"] = [
        {"path": k[0], "component": k[1], "n": v}
        for k, v in rank(na_paths, 12)]
    summary["parse"] = parse_accounting(per_record)
    summary["records_engine_refused"] = sum(
        1 for r in per_record if r["rudof_quads"] is None)
    (RESULTS / "summary.json").write_text(json.dumps(summary, indent=1))
    print(json.dumps({k: v for k, v in summary.items()
                      if k in ("n", "pct_records_with_l1_violation",
                               "pct_records_with_any_defect",
                               "pct_defects_preventable")}, indent=1))


def parse_accounting(per_record: list[dict]) -> dict:
    """Did the engine actually read what it was given?

    Every result a validator can report is a statement about a triple it holds.
    A parser that drops a triple it dislikes, and then reports `conforms: true`,
    has answered a question nobody asked - and a record can be made to pass by
    embedding a malformed IRI in it. That was rudof's worse bug, found by the
    retired pySHACL cross-check and fixed in 0.3.8. The check outlives the
    cross-check because it never needed a second SHACL engine: it compares the
    triple count of the file *we staged* with the quad count rudof loaded from
    it. Zero difference, or a raised error, are the two acceptable answers.
    """
    read = [r for r in per_record if r["rudof_quads"] is not None]
    refused = [r for r in per_record if r["rudof_quads"] is None]
    diffs = [r["staged_triples"] - r["rudof_quads"]
             for r in read if r["rudof_quads"] != r["staged_triples"]]
    n = len(per_record)
    return {
        "records_read": len(read),
        "records_refused": len(refused),
        # Over the records rudof read. The refused ones are excluded from both
        # sides on purpose: nothing was loaded, so a difference there is the
        # refusal, not a silent drop.
        "staged_triples_total": sum(r["staged_triples"] for r in read),
        "rudof_quads_total": sum(r["rudof_quads"] for r in read),
        "triples_lost_by_rudof": sum(d for d in diffs if d > 0),
        "triples_gained_by_rudof": -sum(d for d in diffs if d < 0),
        "records_with_a_parse_difference": len(diffs),
        "pct_records_affected": round(100 * len(diffs) / n, 2) if n else 0.0,
        "staged_triples_in_refused_records":
            sum(r["staged_triples"] for r in refused),
    }


def rank(counter: Counter, limit: int | None = None) -> list:
    """`Counter.most_common`, but deterministic.

    Counter breaks ties by insertion order, and these counters are filled in
    rdflib set-iteration order, which varies between runs. That made the ranked
    tables in summary.json - and so the tables in the report - reshuffle among
    equal counts on every re-run, with no change in the data. Ties are broken by
    the key instead, so the committed artefacts are byte-stable.
    """
    items = sorted(counter.items(), key=lambda kv: (-kv[1], str(kv[0])))
    return items[:limit] if limit is not None else items


def anonymise(per_record: list[dict]) -> dict[str, str]:
    """Give every record with a defect an opaque label that does not join back.

    This is the load-bearing ethics mechanism of the experiment, so it is worth
    being explicit about what broke and why the replacement is different.

    An earlier version of this script drew the label from a shuffle of the
    manifest order under a fixed seed. Both halves of that are committed - the
    seed was a constant in this file, and data/manifest.csv carries the row
    order - so the mapping was invertible in about eight lines of Python by
    anyone with the repository. results/violations.csv was, in effect, a
    per-record defect count keyed by dataset IRI and source catalogue: exactly
    the leaderboard this experiment undertook not to publish, and the write-up
    asserted the opposite.

    The label is now a function of the record's own defect content and of
    nothing else. Records are ordered by defect signature and numbered in that
    order, so reproducing the ordering requires the signatures, which require
    the harvested graphs, which are not committed. manifest.csv and
    violations.csv therefore share no ordering information at all.

    Records whose signatures are equal keep their relative input order. That
    leaks nothing: their rows are byte-identical apart from the label, so
    knowing which of them holds a given label says no more than the group
    already says about all of its members.
    """
    def signature(pr: dict) -> tuple:
        return (
            -len(pr["defects"]),
            tuple(sorted(
                f"{d['layer']}|{d['component']}|{d['focus_class']}|{d['path']}"
                for d in pr["defects"])),
        )

    with_defects = sorted((p for p in per_record if p["defects"]), key=signature)
    return {pr["key"]: f"r{i:04d}" for i, pr in enumerate(with_defects)}


def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    if n == 0:
        return (0.0, 0.0)
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * ((p * (1 - p) / n + z * z / (4 * n * n)) ** 0.5) / d
    return (round(100 * max(0.0, c - h), 1), round(100 * min(1.0, c + h), 1))


DANGLING: list[str] = []


def build_summary(per_record, frame, parse_failures, have_links) -> dict:
    n = len(per_record)
    strata = frame["strata"]
    N = frame["n_population"]

    def rate(pred) -> dict:
        k = sum(1 for r in per_record if pred(r))
        # Horvitz-Thompson: reweight each stratum back to its population share
        num = den = 0.0
        by_cat = defaultdict(list)
        for r in per_record:
            by_cat[r["catalogue"]].append(pred(r))
        for cat, flags in by_cat.items():
            w = strata[cat]["N"] / len(flags)
            num += w * sum(1 for f in flags if f)
            den += w * len(flags)
        cat_rates = sorted(100 * sum(f for f in v) / len(v) for v in by_cat.values())

        # Proper stratified variance for the H-T estimate. The Wilson interval
        # beside pct_sample is a binomial interval on the sample proportion and
        # is correct *for that quantity only*: this is not a uniform random
        # sample, so it says nothing about the population. This one does.
        #   Var(p_st) = sum_h W_h^2 (1 - f_h) p_h(1 - p_h) / (n_h - 1)
        var = 0.0
        for cat, flags in by_cat.items():
            n_h, N_h = len(flags), strata[cat]["N"]
            if n_h < 2:
                continue
            p_h = sum(1 for f in flags if f) / n_h
            W_h = N_h / den if den else 0.0
            var += W_h * W_h * (1 - n_h / N_h) * p_h * (1 - p_h) / (n_h - 1)
        p_st = num / den if den else 0.0
        half = 1.96 * var ** 0.5

        return {
            "k": k, "n": n,
            "pct_sample": round(100 * k / n, 1),
            "ci95_sample": wilson(k, n),
            "pct_population_weighted": round(100 * num / den, 1) if den else 0.0,
            "ci95_population_weighted": [round(100 * max(0.0, p_st - half), 1),
                                         round(100 * min(1.0, p_st + half), 1)],
            "pct_equal_weight_per_catalogue":
                round(sum(cat_rates) / len(cat_rates), 1) if cat_rates else 0.0,
            "catalogue_rate_quartiles": [
                round(cat_rates[0], 1),
                round(cat_rates[len(cat_rates) // 4], 1),
                round(cat_rates[len(cat_rates) // 2], 1),
                round(cat_rates[(3 * len(cat_rates)) // 4], 1),
                round(cat_rates[-1], 1),
            ] if cat_rates else [],
            "n_catalogues_all_conformant":
                sum(1 for v in by_cat.values() if not any(v)),
            "n_catalogues": len(by_cat),
        }

    defects = [d for r in per_record for d in r["defects"]]
    comp_counts = Counter((d["layer"], d["label"]) for d in defects)
    path_counts = Counter((d["focus_class"], d["path"], d["label"])
                          for d in defects if d["layer"] in ("L1", "L2"))
    prev = sum(1 for d in defects if d["bucket"] == "preventable")

    # The generated DCAT-AP shapes put each constraint in its own property
    # shape, so one underlying mistake - a literal where an IRI is required -
    # comes back as both sh:class and sh:nodeKind. Count distinct (record,
    # focus class, path) sites too, so the taxonomy has a unit that is not an
    # artefact of how the profile was generated.
    sites = {(i, d["focus_class"], d["path"], d["bucket"])
             for i, r in enumerate(per_record) for d in r["defects"]}
    sites_prev = sum(1 for s in sites if s[3] == "preventable")

    # The floor under the second headline: only the defect kinds the spec's
    # own "preventable at entry" list names.
    listed = sum(1 for d in defects
                 if d["bucket"] == "preventable" and d["component"] in SPEC_LISTED)

    # How the sample was actually drawn, so a reader can judge for themselves
    # whether n=372 of N=33,228 supports anything. This is NOT a uniform random
    # sample: the floor and the cap make inclusion probability vary by two
    # orders of magnitude between strata.
    incl = {c: v["n"] / v["N"] for c, v in strata.items()}
    rec_w = [strata[r["catalogue"]]["N"] / strata[r["catalogue"]]["n"]
             for r in per_record]
    kish = (len(rec_w) * sum(w * w for w in rec_w) / sum(rec_w) ** 2) if rec_w else 1.0
    design = {
        "sampling_fraction": round(n / N, 5),
        "inclusion_prob_min": round(min(incl.values()), 6),
        "inclusion_prob_max": round(max(incl.values()), 6),
        "inclusion_prob_ratio": round(max(incl.values()) / min(incl.values())),
        "strata_at_floor": sum(1 for v in strata.values()
                               if v["n"] == frame["stratum_floor"]),
        "strata_at_cap": sum(1 for v in strata.values()
                             if v["n"] == frame["stratum_cap"]),
        "strata_fully_censused": sum(1 for v in strata.values() if v["n"] == v["N"]),
        "kish_design_effect": round(kish, 2),
        "effective_n": round(len(rec_w) / kish) if kish else n,
    }

    # (layer, component, human label) - the label is carried on the defect, so
    # the L3 checks describe themselves rather than showing a class name.
    comp_totals = Counter((d["layer"], d["component"], d["label"]) for d in defects)

    return {
        "generated_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "n": n,
        "n_population": N,
        "n_catalogues": frame["n_catalogues"],
        "parse_failures": parse_failures,
        "linkcheck_available": have_links,
        "records_with_l1_violation": rate(lambda r: r["l1"] > 0),
        "records_with_l1_or_l2_violation": rate(lambda r: r["l1"] + r["l2"] > 0),
        "records_with_any_defect": rate(lambda r: r["l1"] + r["l2"] + r["l3"] > 0),
        "records_with_l3_defect": rate(lambda r: r["l3"] > 0),
        # upper bound: what the rate would be if every unresolvable reference
        # were charged as a violation instead of set aside
        "records_upper_bound": rate(
            lambda r: r["l1"] + r["l2"] + r["l3"] + r["not_assessable"] > 0),
        "records_untagged_title": rate(lambda r: r["untagged_title"]),
        # descriptive: the aggregator machine-translates titles and descriptions
        # into every EU language and tags them with a BCP-47 -t-...-t0-mt
        # transform extension. All of them are stripped before validation.
        "mt_literals_stripped": sum(r["mt_literals"] for r in per_record),
        "records_with_mt_literals":
            sum(1 for r in per_record if r["mt_literals"] > 0),
        "records_without_description": rate(lambda r: not r["has_description"]),
        "pct_records_with_l1_violation":
            round(100 * sum(1 for r in per_record if r["l1"] > 0) / n, 1),
        "pct_records_with_any_defect":
            round(100 * sum(1 for r in per_record if r["l1"] + r["l2"] + r["l3"] > 0) / n, 1),
        "total_defects": len(defects),
        "total_preventable": prev,
        "pct_defects_preventable": round(100 * prev / len(defects), 1) if defects else 0.0,
        "defect_sites_total": len(sites),
        "defect_sites_preventable": sites_prev,
        "pct_defect_sites_preventable":
            round(100 * sites_prev / len(sites), 1) if sites else 0.0,
        "defects_preventable_spec_listed": listed,
        "pct_defects_preventable_spec_listed":
            round(100 * listed / len(defects), 1) if defects else 0.0,
        "design": design,
        "bucket_mapping": [
            {"layer": k[0], "component": k[1], "label": k[2],
             "bucket": "preventable" if k[0] in ("L1", "L2") else "not preventable",
             "on_spec_list": k[1] in SPEC_LISTED, "n": v}
            for k, v in rank(comp_totals)],
        "value_shapes": [
            {"path": k[0], "shape": k[1], "n": v}
            for k, v in sorted(VALUE_SHAPES.items(),
                               key=lambda kv: (kv[0][0], -kv[1], kv[0][1]))],
        "defects_per_record_median": sorted(
            r["l1"] + r["l2"] + r["l3"] for r in per_record)[n // 2],
        "not_assessable_total": sum(r["not_assessable"] for r in per_record),
        # what share of everything a validator hands the operator is unfixable
        "pct_results_not_assessable": round(
            100 * sum(r["not_assessable"] for r in per_record)
            / (sum(r["not_assessable"] for r in per_record) + len(defects)), 1)
        if defects else 0.0,
        "engine_errors_total": sum(r["engine_errors"] for r in per_record),
        "scaffolding_results_total": sum(r["scaffolding_results"] for r in per_record),
        "dangling_property_shapes_dropped": DANGLING,
        "by_layer": {
            "L1": sum(r["l1"] for r in per_record),
            "L2": sum(r["l2"] for r in per_record),
            "L3": sum(r["l3"] for r in per_record),
        },
        "by_component": dict(rank(Counter(f"{d['layer']}:{d['component']}"
                                            for d in defects))),
        "taxonomy": [{"layer": k[0], "label": k[1], "n": v}
                     for k, v in rank(comp_counts)],
        "top_paths": [{"class": k[0], "path": k[1], "label": k[2], "n": v}
                      for k, v in rank(path_counts, 20)],
    }


if __name__ == "__main__":
    main()
