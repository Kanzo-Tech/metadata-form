#!/usr/bin/env python3
"""Published errors — validate the harvested records and classify every defect.

Engine: rudof, through the published `@kanzo-tech/rudof-wasm` package, loaded
exactly as `src/engine/RudofEngine.ts` loads it. This is the engine the library
ships and the engine the form runs on commit, so it is the engine whose verdict
the paper's claim is about.

It was not always the only one. An earlier round of this experiment ran the
whole corpus through pySHACL as well and diffed the two reports defect by
defect. That comparison did its job: it surfaced two real rudof defects — a
validation bypass in which the Turtle parser silently discarded triples with
malformed IRIs, and `sh:targetClass` failing to select through the
`rdfs:subClassOf` closure. Both are fixed and published in
`@kanzo-tech/rudof-wasm@0.3.8`, and `conformance.py` now holds the minimal
reproducer for each with its expected answer taken from the specification's own
words. A second SHACL implementation is a workshop instrument, not evidence, so
it is no longer in the pipeline and no number here depends on one.

rdflib is still here, and is not an exception to that: it parses, cleans and
re-serializes the harvested Turtle. It is an RDF toolkit, not a SHACL engine,
and it decides nothing about conformance.

The pipeline is three stages:

  stage      parse each raw record with rdflib, clean it, merge the subclass
             axioms and the referenced-IRI types, serialize the result to
             data/stage/. One graph construction, written down once.
  validate   hand data/stage/ to rudof_validate.mjs — one process, one wasm
             instance, shapes parsed once per layer.
  classify   triage every result into defect / scaffolding / not assessable and
             count.

Three layers of checking, kept separate on purpose:

  L1  DCAT-AP 3.0.1 SHACL exactly as SEMIC publishes it. This is the profile the
      records claim, so this is the honest "violates its own profile" number.
  L2  constraints DCAT-AP 3.0.1 states in prose but does not express in SHACL
      (EU authority-table membership), plus the sh:uniqueLang constraints the
      official Health-RI formalisation of HealthDCAT-AP applies, plus
      sh:minLength 1 on the two mandatory literals. Generated by vocab_shapes.py.
  L3  defects no SHACL profile can express: a dead distribution link, a record
      whose last modification contradicts its own declared update frequency, and
      a placeholder value that is structurally perfect and semantically empty.

L1 and L2 are expressible in SHACL and L3 is not, which is the only thing the
"preventable" bucket in this file's output means. It used to mean more: this
docstring asserted that L1 and L2 are "preventable at entry by construction - a
shape-driven form cannot submit a graph that violates a shape it is generated
from". That was reasoning, not measurement, and `preventability.py` has since
measured it against the form this library actually renders. The answer is not
the one the sentence assumed: prevention by the *control* is 0 of 1,369, because
DCAT-AP's generated SHACL splits one predicate across up to four property shapes
and the form renders one open control per shape. The 1,321 are prevented by
commit-time validation instead — a real gate, but a different claim, and one
that depends on the host application honouring `form.isValid`.

Read `results/preventability.md` before quoting anything from here as a
statement about forms. This file's job is the records.

Before validating, each record graph is cleaned of things the aggregator added
rather than the publisher: dqv quality annotations, and machine-translated
literals (BCP-47 `-t-...-t0-mt*` transform tags). See "threats to validity".

Outputs (all committed, all aggregate or anonymised):
  results/summary.json
  results/violations.csv     one row per defect, record key replaced by an
                             opaque label derived from the record's own defect
                             content - see anonymise() for why that matters
  results/wild-errors.md     written by report.py

Scratch (not committed, same reason as data/raw/):
  data/stage/                the staged validation graphs, keys.json, meta.json
  data/stage/rudof-raw.json  rudof's raw report, read back by preventability.py

Usage: python validate.py
"""

